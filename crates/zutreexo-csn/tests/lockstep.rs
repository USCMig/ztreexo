fn fixture_dir() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("../..")
        .join("fixtures")
}

fn load_slice(name: &str) -> Option<Vec<zebra_chain::block::Block>> {
    use zebra_chain::serialization::ZcashDeserialize;
    let text = std::fs::read_to_string(fixture_dir().join(format!("{name}.jsonl"))).ok()?;
    let mut blocks = Vec::new();
    for line in text.lines() {
        let line = line.trim();
        if line.is_empty() {
            continue;
        }
        let bytes = hex::decode(line.trim_matches('"')).expect("bad hex in fixture");
        blocks.push(zebra_chain::block::Block::zcash_deserialize(&bytes[..]).expect("bad block"));
    }
    Some(blocks)
}

/// Real mainnet nullifiers, driven through the bundle and verified from roots
/// alone.
///
/// The transparent fields are cleared rather than tolerated. A window replay
/// cannot resolve spends that predate it, and rather than teach the compact
/// node to accept unproven deletions for the sake of a test — which would
/// weaken the one property this crate exists to provide — the test restricts
/// itself to the half that is exact over a window.
#[test]
fn real_mainnet_nullifiers_verify_from_roots_alone() {
    let mut ran = 0usize;
    for name in [
        "sapling-activation",
        "nu5-orchard",
        "sandblasting",
        "ironwood-activation",
    ] {
        let Some(blocks) = load_slice(name) else {
            eprintln!("SKIPPED {name}: fixture not present");
            continue;
        };

        let mut bridge = ChainAccumulators::new(DEPTH).unwrap();
        let mut csn = CompactState::new(DEPTH).unwrap();
        let mut nullifiers = 0usize;

        for (index, block) in blocks.iter().enumerate() {
            let mut summary = summarize_block(block).expect("fixture block would not parse");
            // Renumber to a contiguous chain from zero: the slice starts
            // mid-chain and both sides enforce contiguity.
            summary.height = index as u32;
            summary.transparent_spends.clear();
            summary.transparent_creates.clear();

            nullifiers += summary.nullifier_count();

            let (_, bundle) = apply_and_prove(&mut bridge, &summary, ApplyOptions::default())
                .unwrap_or_else(|e| panic!("{name} block {index}: bridge failed: {e}"));
            let wire = BlockProofBundle::from_bytes(&bundle.to_bytes()).unwrap();
            csn.apply_bundle(&summary, &wire)
                .unwrap_or_else(|e| panic!("{name} block {index}: compact node rejected: {e}"));

            assert_eq!(
                csn.nullifier_roots(),
                bridge.nullifier_roots(),
                "{name}: nullifier roots diverged at block {index}"
            );
        }

        assert!(nullifiers > 0, "{name}: no nullifiers exercised");
        eprintln!("{name}: {nullifiers} nullifiers verified from roots alone");
        ran += 1;
    }

    if ran == 0 {
        eprintln!("SKIPPED: no fixtures present; this test verified nothing.");
    }
}
